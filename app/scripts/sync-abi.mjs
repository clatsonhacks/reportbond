// Regenerates lib/abi.ts from the Foundry build. Run after changing the contract: pnpm sync-abi
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(
  readFileSync(path.join(here, "../../contracts/out/ReportBond.sol/ReportBond.json"), "utf8"),
);
const out = `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit.
export const reportBondAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(path.join(here, "../lib/abi.ts"), out);
console.log(`lib/abi.ts: ${artifact.abi.length} entries`);
